"""cs_msad_mqsad: the GPU fixture for v_msad_u8 and v_mqsad_u32_u8, run here on the CPU too.

Standard library only; no GPU, no LLVM, no game files.

runtime/test/shaders/cs_msad_mqsad.asm has lane 0 of a wave32 group store two masked byte-SADs and the four
dwords of one v_mqsad_u32_u8 (derivations in its header). This runs the fixture (generated by
tests/semantic/regen_fixtures.py) through spirv_mini_interp, compares the eight words with the ISA
definitions computed here, and checks that check.py and scripts/run_gpu_tests.py expect the same words on
the GPU.
"""

import os
import re
import struct
import unittest

import support
import spirv_mini_interp as si

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
M32 = 0xFFFFFFFF

# 4 user SGPRs (the output V#), workgroup id in s4, 512 bytes of LDS (LDS_SIZE 1), 32x1x1 threads.
FSSM = bytearray(0x148)
struct.pack_into("<4I", FSSM, 0x138, 0x8088, 32, 1, 1)
FSSM = bytes(FSSM)
VSHARP = [0, 0, 0x1000, 0x31016FAC]

# The shader's operands (cs_msad_mqsad.asm): 64-bit S0 in v2:v3, S1 in v4, the four accumulators in v6..v9.
S0 = 0x0001020304050607
S1 = 0x00000201
ACCS = [0xFFFFFFF0, 0xFFFFFFFF, 0x80000000, 0x12345678]


def msad(x: int, y: int, acc: int) -> int:
    """v_msad_u8: S2 + the byte differences, skipping each byte where S1's byte is 0, mod 2^32."""
    total = 0
    for i in range(4):
        xb, yb = (x >> (8 * i)) & 0xFF, (y >> (8 * i)) & 0xFF
        if yb:
            total += abs(xb - yb)
    return (acc + total) & M32


def mqsad(s0: int, s1: int, accs) -> list:
    """v_mqsad_u32_u8: D[k] = S2[k] + the masked byte SAD of the 32-bit window S0[8k+31 : 8k]."""
    return [msad((s0 >> (8 * k)) & M32, s1, accs[k]) for k in range(4)]


EXPECTED = [
    msad(0x10203040, 0x00100020, 0),  # 0x30, bytes 1 and 3 masked
    msad(0, 0x01010101, 0xFFFFFFF0),  # 0xFFFFFFF4, wraps
    *mqsad(S0, S1, ACCS),  # 0xFFFFFFFA 7 0x80000006 0x1234567C
    msad(0xFFFFFFFF, 0, 0xDEADBEEF),  # all four bytes masked, S2 unchanged
    msad(1, 0x0000FF00, 0),
]  # only byte 1 counts: 0xFF


class MsadMqsadFixture(unittest.TestCase):
    def test_reference(self):
        self.assertEqual(
            EXPECTED,
            [0x30, 0xFFFFFFF4, 0xFFFFFFFA, 7, 0x80000006, 0x1234567C, 0xDEADBEEF, 0xFF],
        )

    def test_translated_shader(self):
        spv = support.translate_fixture("cs_msad_mqsad", fssm=FSSM)
        mem = si.run_workgroup(
            spv,
            1,
            32,
            inputs_for=lambda i: {
                "%wg_id": (0, 0, 0),
                "%local_id": (i, 0, 0),
                "%sg_lane": i,
            },
            push_constants=VSHARP + [0] * 28,
            memory={},
        )
        self.assertEqual(sorted(mem), [4 * k for k in range(8)])
        for k, want in enumerate(EXPECTED):
            with self.subTest(word=k):
                self.assertEqual(mem[4 * k], want)

    def test_destination_and_s2_do_not_overlap(self):
        # v_mqsad_u32_u8 writes four VGPRs; reading them back from v10..v13 (and S2 from v6..v9) means a
        # translator that clobbered a source cannot pass the word check above.
        with open(
            os.path.join(ROOT, "runtime", "test", "shaders", "cs_msad_mqsad.asm"),
            encoding="utf-8",
        ) as f:
            text = f.read()
        self.assertIn("v_mqsad_u32_u8 v[10:13], v[2:3], v4, v[6:9]", text)

    def test_gpu_runners_expect_the_same_words(self):
        for rel in (
            ("runtime", "test", "shaders", "check.py"),
            ("scripts", "run_gpu_tests.py"),
        ):
            with open(os.path.join(ROOT, *rel), encoding="utf-8") as f:
                text = f.read()
            m = re.search(r'"cs_msad_mqsad"\)?[,:]\s*\[([^\]]*)\]', text)
            with self.subTest(file="/".join(rel)):
                self.assertIsNotNone(m)
                got = [
                    int(v, 0)
                    for v in m.group(1).replace("\n", " ").split(",")
                    if v.strip()
                ]
                self.assertEqual(got, EXPECTED)


if __name__ == "__main__":
    unittest.main()
